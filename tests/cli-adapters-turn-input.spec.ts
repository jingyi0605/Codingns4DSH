import assert from 'node:assert/strict'
import test from 'node:test'
import type { CodingNsCliMessage, CodingNsCliTurnInput } from '../src/shared/contracts/cli-adapter.js'
import { createCliAdaptersFeature } from '../src/host/cli-adapters/feature.js'
import { CodingNsCliAdapterRegistry } from '../src/host/cli-adapters/registry.js'
import { CodingNsRpcTable } from '../src/host/rpc-table.js'
import { FeatureRegistry } from '../src/features/registry.js'

async function fixture() {
  const calls: CodingNsCliTurnInput[] = []
  let stream: ((options: unknown, next: () => AsyncIterable<unknown>) => AsyncIterable<unknown>) | undefined
  const registry = new CodingNsCliAdapterRegistry([{
    descriptor: { id: 'codex', name: 'Codex' },
    async detect() { return { installed: true, version: 'fixture', command: 'fake-codex' } },
    async listModels() { return { groups: [], currentModel: null, currentEffort: null } },
    async *executeTurn(input) {
      calls.push(input)
      yield { type: 'text-delta', text: 'Done' }
      yield { type: 'finish', reason: 'stop' }
    },
  }])
  registry.setSession('external', { adapterId: 'codex', modelId: 'selected-codex' })
  const features = new FeatureRegistry({
    rpc: new CodingNsRpcTable(),
    events: {
      on(_name, listener) { stream = listener; return () => { stream = undefined } },
      emit() {},
    },
  })
  features.register(createCliAdaptersFeature({ registry }))
  await features.start('cliAdapters')
  return {
    calls,
    async send(messages: readonly CodingNsCliMessage[]) {
      for await (const _ of stream!({ sessionId: 'external', messages }, async function* () { assert.fail('External routing was lost') })) {}
      return calls.at(-1)!
    },
    stop: () => features.disable('cliAdapters'),
  }
}

const path = 'D:\\Videos\\sample.mp4'
const prompt = `Split "${path}" at 05:00 and save both segments to Desktop.`
const human: CodingNsCliMessage = { id: 'human-input', role: 'user', source: { kind: 'user' }, content: [{ type: 'text', text: prompt }] }
const modelNotice: CodingNsCliMessage = {
  id: 'native-model-notice', role: 'user', source: { kind: 'model-selection', form: 'notice', summary: 'Codex -> native' },
  content: [{ type: 'text', text: '[model changed: assistant turns above this point were generated by Codex; the session continues with native]' }],
}

test('model-switch notices never replace the current human input on consecutive external turns', async () => {
  const f = await fixture()
  try {
    assert.equal((await f.send([human, modelNotice])).prompt, prompt)
    const next = { ...human, id: 'next-human', content: [{ type: 'text', text: path }] }
    const history: CodingNsCliMessage[] = [human, modelNotice, { role: 'assistant', content: 'Previous reply' }]
    assert.equal((await f.send([...history, next, { ...modelNotice, id: 'next-notice' }])).prompt, path)
  } finally { await f.stop() }
})

test('model-switch notices preserve translated human input and its reference context', async () => {
  const f = await fixture()
  try {
    const translated = { ...human, source: { kind: 'user', codingnsTranslationInput: { original: prompt, translated: 'Translated video request', targetLanguage: 'en' } } }
    const reference: CodingNsCliMessage = { role: 'user', source: { kind: 'session-reference', form: 'recall' }, content: 'Output directory from another session' }
    const input = await f.send([translated, reference, modelNotice])
    assert.equal(input.prompt, 'Translated video request\n\nOutput directory from another session')
    assert.equal(input.messages.some(message => message.source?.kind === 'session-reference'), false)
  } finally { await f.stop() }
})

test('plugin-owned continuations still win over old human history and trailing model notices', async () => {
  const f = await fixture()
  try {
    for (const source of [{ kind: 'model-selection', form: 'notice' }, { kind: 'plugin', plugin: 'codingns4dsh', form: 'notice' }]) {
      const continuation: CodingNsCliMessage = {
        id: 'codingns-external-step-1-fixture', role: 'user', source,
        content: [{ type: 'text', text: 'Continue after the external tool completed.' }],
      }
      const input = await f.send([human, { role: 'assistant', content: 'Tool completed' }, continuation, modelNotice])
      assert.equal(input.prompt, 'Continue after the external tool completed.')
    }
  } finally { await f.stop() }
})
